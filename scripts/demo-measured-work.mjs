import {
  mkdtemp,
  mkdir,
  readFile,
  writeFile,
  rm,
  readdir,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:http';
import { performance } from 'node:perf_hooks';
import { Wallet } from 'ethers';
import {
  initializeNode,
  exportMission,
  readJson,
  loadNode,
  signDetachedReview,
  importDetachedReview,
  signOutcome,
  importOutcome,
  verifyEvidenceBundle,
} from '../src/alpha/node.js';
import { digest } from '../src/alpha/mission.js';
import { verifyMeasurementArtifacts } from '../src/alpha/measurement.js';
import { operate } from '../src/alpha/runtime/engine.js';
import { qualifyNode } from '../src/alpha/qualification.js';

const out = resolve(process.argv[2] ?? 'alpha-measured-output');
await mkdir(out, { recursive: true });
if ((await readdir(out)).length)
  throw new Error(
    'Choose an empty output directory to preserve earlier measurements',
  );
const dir = await mkdtemp(join(tmpdir(), 'alpha-measured-work-'));
let health;
const rows = Array.from(
  { length: 5000 },
  (_, i) => `record-${(i * 7919) % 2500}`,
);
const expected = [...new Set(rows)],
  target = join(dir, 'service.json');
const sleep = (ms) =>
  new Promise((resolve) => setTimeout(resolve, Math.max(0, ms)));
const rateUsdPerCpuHour = 1;
async function execute() {
  const { algorithm } = await readJson(target);
  const cpu = process.cpuUsage(),
    started = performance.now();
  let result;
  if (algorithm === 'baseline') {
    result = [];
    for (const item of rows) if (!result.includes(item)) result.push(item);
  } else if (algorithm === 'set') result = [...new Set(rows)];
  else throw new Error('Unknown explicitly configured algorithm');
  const used = process.cpuUsage(cpu);
  return {
    algorithm,
    cpuSeconds: (used.user + used.system) / 1e6,
    wallMs: performance.now() - started,
    outputHash: digest(result),
    correct: JSON.stringify(result) === JSON.stringify(expected),
  };
}
async function measureWindow() {
  const start = (Math.floor(Date.now() / 1000) + 1) * 1000,
    end = start + 1000;
  await sleep(start - Date.now());
  const measured = await execute();
  if (Date.now() >= end)
    throw new Error(
      'Work exceeded the one-second measurement window; no comparable result recorded',
    );
  await sleep(end - Date.now());
  return {
    ...measured,
    startedAt: new Date(start).toISOString(),
    endedAt: new Date(end).toISOString(),
  };
}
try {
  const reviewer = Wallet.createRandom();
  await initializeNode(dir, {
    ensName: 'measured.alpha.node.agi.eth',
    reviewer: reviewer.address,
  });
  await writeFile(target, JSON.stringify({ algorithm: 'baseline' }));
  const baseline = await measureWindow();
  if (!baseline.correct)
    throw new Error('Baseline does not meet the reference acceptance criteria');
  const contract = {
    taskKey: 'ordered-deduplication-5000',
    method: 'paired-value-v1',
    unit: 'USD',
    periodSeconds: 1,
    workloadHash: digest(rows),
    acceptanceHash: digest({
      expectedOutputHash: digest(expected),
      rule: 'Exact ordered reference equality',
    }),
  };
  const baselineCost = (baseline.cpuSeconds / 3600) * rateUsdPerCpuHour;
  const mission = {
    id: 'measured-deduplication',
    title: 'Measured ordered-deduplication experiment',
    objective:
      'Compare two explicitly supplied implementations on an actual local workload. After signed review, switch only the configured algorithm and verify exact output equality. CPU use is measured; dollar equivalents use an illustrative rate and are not invoices or profit.',
    measurement: contract,
    sources: [
      {
        id: 'baseline',
        title: 'Actual local baseline and illustrative pricing',
        text: JSON.stringify({
          baseline,
          rateUsdPerCpuHour,
          pricingBasis: 'modeled',
          records: rows.length,
          unique: expected.length,
        }),
      },
    ],
    opportunities: [
      {
        id: 'set-dedupe',
        title: 'Evaluate the supplied Set implementation',
        benefit: baselineCost * 0.5,
        cost: 0,
        probability: 0.8,
        downside: 0,
        sourceIds: ['baseline'],
        rationale:
          'Hypothesis: the supplied Set implementation uses less CPU with exactly equal output. Must be measured; neither implementation was generated by the node.',
      },
    ],
    policy: {
      maxCost: 1,
      maxDownside: 0,
      minExpectedNet: 0,
      stressBenefitBps: 5000,
    },
    unit: 'Modeled USD per fixed workload',
  };
  health = createServer(async (_, res) => {
    try {
      res.end(JSON.stringify({ healthy: (await execute()).correct }));
    } catch {
      res.writeHead(500);
      res.end();
    }
  });
  await new Promise((r) => health.listen(0, '127.0.0.1', r));
  const pipeline = JSON.parse(
    await readFile(new URL('../examples/alpha/pipeline.json', import.meta.url)),
  );
  await writeFile(
    join(dir, 'pipeline.json'),
    JSON.stringify({
      ...pipeline,
      sourceKind: 'mission',
      source: 'source.json',
      policy: mission.policy,
    }),
  );
  await writeFile(
    join(dir, 'source.json'),
    JSON.stringify({
      schema: 1,
      observedAt: new Date().toISOString(),
      mission,
    }),
  );
  await writeFile(
    join(dir, 'engine.json'),
    JSON.stringify({
      schema: 1,
      actions: {
        'set-dedupe': {
          kind: 'json-set',
          root: dir,
          file: 'service.json',
          pointer: ['algorithm'],
          value: 'set',
          healthUrl: `http://127.0.0.1:${health.address().port}`,
          healthField: 'healthy',
          healthValue: true,
          timeoutMs: 3000,
        },
      },
    }),
  );
  const first = await operate(dir),
    id = first.discovery.missionId;
  if (!id)
    throw new Error('Experiment did not pass the analytical admission policy');
  let bundle = await readJson(
    (await exportMission(dir, id, join(dir, 'review'))).evidence,
  );
  await importDetachedReview(
    dir,
    await signDetachedReview(
      bundle,
      'accepted',
      'Automated fixture reviewer checked the bounded experiment. This is not an independent person.',
      reviewer.privateKey,
    ),
  );
  const applied = await operate(dir);
  if (applied.progress[0]?.status !== 'applied')
    throw new Error('Reviewed algorithm change did not apply');
  const candidate = await measureWindow();
  const artifact = {
    schema: 1,
    actualCpuMeasurement: true,
    inputKind: 'generated reproducible workload',
    workloadHash: contract.workloadHash,
    records: rows.length,
    expectedUnique: expected.length,
    baseline,
    candidate,
    rateUsdPerCpuHour,
    pricingBasis: 'modeled',
    limitation:
      'Supplied implementations and generated data; one paired local measurement is not a causal production benchmark or measured financial return.',
  };
  const content = JSON.stringify(artifact, null, 2) + '\n',
    sha256 = digest(content),
    artifactDir = join(out, 'artifacts');
  await mkdir(artifactDir);
  await writeFile(join(artifactDir, `${sha256.slice(2)}.bin`), content);
  const window = (m) => ({
    startedAt: m.startedAt,
    endedAt: m.endedAt,
    workUnits: rows.length,
    acceptedUnits: m.correct ? rows.length : 0,
    grossValueUsd: 0,
    operatingCostUsd: (m.cpuSeconds / 3600) * rateUsdPerCpuHour,
  });
  const measurement = {
    kind: 'paired-value-v1',
    evidenceClass: 'modeled',
    contract,
    baseline: window(baseline),
    candidate: window(candidate),
    overhead: {
      inferenceUsd: 0,
      executionUsd: 0,
      reviewUsd: 0,
      infrastructureUsd: 0,
      settlementUsd: 0,
      otherUsd: 0,
    },
    humanMinutes: 0,
    artifacts: [
      {
        sha256,
        description:
          'Actual paired CPU and correctness observations with explicitly modeled dollar equivalents.',
      },
    ],
    observedAt: new Date().toISOString(),
    evidence:
      'Actual local CPU measurements; illustrative pricing; automated fixture reviewer. Excluded from observed economic qualification and learning.',
  };
  bundle = await readJson(
    (await exportMission(dir, id, join(dir, 'review'))).evidence,
  );
  await importOutcome(
    dir,
    await signOutcome(bundle, measurement, reviewer.privateKey),
  );
  bundle = await readJson((await exportMission(dir, id, out)).evidence);
  const verification = verifyEvidenceBundle(bundle),
    artifacts = await verifyMeasurementArtifacts(measurement, artifactDir);
  const qualification = await qualifyNode(dir);
  if (qualification.gatePassed || qualification.metrics.measuredMissions !== 0)
    throw new Error('Modeled economics must never qualify as observed value');
  const result = {
    ...artifact,
    actionApplied: true,
    signedOutcome: true,
    verification,
    artifactsVerified: artifacts.verified.length,
    cpuReductionFraction:
      baseline.cpuSeconds > 0
        ? 1 - candidate.cpuSeconds / baseline.cpuSeconds
        : null,
    qualification,
    productionQualified: false,
    independentPeople: false,
    tokenPayments: false,
  };
  await writeFile(
    join(out, 'measurement.json'),
    JSON.stringify(result, null, 2) + '\n',
  );
  console.log(
    JSON.stringify({
      output: out,
      actualCpuMeasurement: true,
      baselineCpuSeconds: baseline.cpuSeconds,
      candidateCpuSeconds: candidate.cpuSeconds,
      outputsEqual: candidate.outputHash === baseline.outputHash,
      actionApplied: true,
      artifactsVerified: artifacts.verified.length,
      economicEvidenceClass: 'modeled',
      productionQualified: false,
    }),
  );
} finally {
  if (health) {
    health.closeAllConnections();
    await new Promise((r) => health.close(r));
  }
  await rm(dir, { recursive: true, force: true });
}
